// Writes the checks the web page runs: Ajv compiled ahead of time, because the policy of the page has no 'unsafe-eval'
// and Ajv at run time needs `new Function`.
//
//   node web/gen-validate.mjs            (from ui/) writes src/web/validate.generated.js and
//                                        src/web/validate-session.generated.js
//
// In: src/web/testing-export.schema.json (the documents of an export) and src/web/testing-sheet-session.schema.json
// (the lines of the recording of a stepped run, `events.jsonl`), copies of the engine's at the commit of engine.lock
// (crates/testing-hub/tests/golden_copy.rs compares them). `web/web.test.mjs` fails when a file is not what this writes.

import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMA = join(here, '..', 'src', 'web', 'testing-export.schema.json');
export const GENERATED = join(here, '..', 'src', 'web', 'validate.generated.js');
export const SESSION_SCHEMA = join(here, '..', 'src', 'web', 'testing-sheet-session.schema.json');
export const SESSION_GENERATED = join(here, '..', 'src', 'web', 'validate-session.generated.js');

/** The text of the module. `unicode: false`: a length in code units, so the code needs no helper of Ajv at run time. */
function generateFrom(file) {
  const schema = JSON.parse(readFileSync(file, 'utf8'));
  const ajv = new Ajv2020.default({ strict: true, allErrors: false, unicode: false, code: { source: true, esm: true, lines: true } });
  const validate = ajv.compile(schema);
  const code = standaloneCode.default(ajv, validate);
  return `// GENERATED by web/gen-validate.mjs from ${basename(file)}. Do not edit.\n// @ts-nocheck\n${code}\n`;
}

/** The check of a document of testing-export/1. */
export function generate() {
  return generateFrom(SCHEMA);
}

/** The check of one line of a recording (testing-sheet-session/1). */
export function generateSession() {
  return generateFrom(SESSION_SCHEMA);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED, generate());
  console.log(`wrote ${GENERATED}`);
  writeFileSync(SESSION_GENERATED, generateSession());
  console.log(`wrote ${SESSION_GENERATED}`);
}

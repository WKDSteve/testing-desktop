// Writes the check of the documents of testing-export/1 that the web page runs: Ajv compiled ahead of time, because the
// policy of the page has no 'unsafe-eval' and Ajv at run time needs `new Function`.
//
//   node web/gen-validate.mjs            (from ui/) writes src/web/validate.generated.js
//
// In: src/web/testing-export.schema.json, a copy of the engine's at the commit of engine.lock
// (crates/testing-hub/tests/golden_copy.rs compares it). `web/validate.test.mjs` fails when the file is not what this
// writes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMA = join(here, '..', 'src', 'web', 'testing-export.schema.json');
export const GENERATED = join(here, '..', 'src', 'web', 'validate.generated.js');

/** The text of the module. `unicode: false`: a length in code units, so the code needs no helper of Ajv at run time. */
export function generate() {
  const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));
  const ajv = new Ajv2020.default({ strict: true, allErrors: false, unicode: false, code: { source: true, esm: true, lines: true } });
  const validate = ajv.compile(schema);
  const code = standaloneCode.default(ajv, validate);
  return `// GENERATED by web/gen-validate.mjs from testing-export.schema.json. Do not edit.\n// @ts-nocheck\n${code}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED, generate());
  console.log(`wrote ${GENERATED}`);
}
